function splitStock(sizes: ProductSize[], total: number): SizeStock {
  if (!sizes.length) return {};
  if (total <= 0) {
    return Object.fromEntries(sizes.map((size) => [size, 0])) as SizeStock;
  }
  const base = Math.floor(total / sizes.length);
  let remainder = total - base * sizes.length;
  return Object.fromEntries(
    sizes.map((size) => {
      const extra = remainder > 0 ? 1 : 0;
      if (remainder > 0) remainder -= 1;
      return [size, base + extra];
    }),
  ) as SizeStock;
}

